def test_17_generated_code_deprioritized_as_graph_seed(mixed_repo: Path) -> None:
    """17. Generated code is deprioritized from active graph seeds in normal retrieval."""
    indexer = Indexer(mixed_repo)
    indexer.index()

    with indexer.session() as con:
        ctx = get_context(con, mixed_repo, "how does authenticate work", intent="UNDERSTAND")
        sym_names = [s.symbol for s in ctx.symbols]
        assert "authenticate" in sym_names
        assert ctx.symbols[0].symbol in ("authenticate", "login_user")


