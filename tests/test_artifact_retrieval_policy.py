def test_33_identical_repo_identical_classification(tmp_path: Path) -> None:
    """33. Two identical directory structures produce bitwise identical file classifications."""
    paths = [
        "src/app.py",
        "tests/test_app.py",
        "dist/bundle.js",
        "vendor/lib.js",
        "src/types.gen.ts",
        "styles.min.css",
        "package-lock.json",
    ]
    classes1 = [classify_file_detailed(p) for p in paths]
    classes2 = [classify_file_detailed(p) for p in paths]
    for c1, c2 in zip(classes1, classes2, strict=True):
        assert c1.category == c2.category
        assert c1.reason == c2.reason
        assert c1.confidence == c2.confidence


def test_34_identical_ranking_determinism() -> None:
    """34. Ranking candidates with artifact categories is strictly deterministic across runs."""
    candidates = [
        {"symbol": "login", "file": "src/auth.py", "category": "SOURCE", "score": 0.5},
        {"symbol": "login", "file": "gen/auth_gen.py", "category": "GENERATED", "score": 0.5},
    ]
    res1 = rank_candidates(candidates, query="login")
    res2 = rank_candidates(candidates, query="login")
    assert [r.file for r in res1] == [r.file for r in res2]
    assert [r.score for r in res1] == [r.score for r in res2]


