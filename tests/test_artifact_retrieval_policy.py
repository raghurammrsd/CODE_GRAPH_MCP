    f.write_text("def temporary(): pass\n", encoding="utf-8")

    indexer = Indexer(repo)
    indexer.index()
    with indexer.session() as con:
        assert con.execute("SELECT count(*) FROM files WHERE path='temp.py'").fetchone()[0] == 1
        assert con.execute("SELECT count(*) FROM symbols WHERE name='temporary'").fetchone()[0] == 1

    f.unlink()
    indexer.index()
