def test_36_binary_never_parsed_as_source(tmp_path: Path) -> None:
    """36. Binary files are never parsed into AST symbols."""
    repo = tmp_path / "bin_repo"
    repo.mkdir()
    # Binary file with .py extension
    (repo / "corrupt.py").write_bytes(b"\x00\x00\x00\x00def parsed(): pass")

    indexer = Indexer(repo)
    indexer.index()
    with indexer.session() as con:
        # corrupt.py must not produce symbols in symbols table
        sym_count = con.execute("SELECT count(*) FROM symbols WHERE path='corrupt.py'").fetchone()[0]
        assert sym_count == 0


def test_37_external_symlink_not_followed(tmp_path: Path) -> None:
    """37. External symlinks pointing outside repository boundary raise SecurityError and are not indexed."""
    repo = tmp_path / "safe_repo"
    repo.mkdir()
    outside = tmp_path / "outside.py"
    outside.write_text("def secret(): pass\n", encoding="utf-8")

    link = repo / "link_to_outside.py"
    try:
        link.symlink_to(outside)
    except OSError:
        pytest.skip("Symlinks not supported in environment")

    with pytest.raises(SecurityError):
        safe_path(repo, "link_to_outside.py")
