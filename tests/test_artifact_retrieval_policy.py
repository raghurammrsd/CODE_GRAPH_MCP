def test_20_source_code_remains_preferred_in_ranking() -> None:
    """20. Handwritten source is ranked above generated, vendor, and bundles."""
    candidates = [
        {"symbol": "authenticate", "file": "vendor/library.js", "category": "VENDOR", "score": 0.8},
        {"symbol": "authenticate", "file": "generated/client.py", "category": "GENERATED", "score": 0.8},
        {"symbol": "authenticate", "file": "src/auth.py", "category": "SOURCE", "score": 0.8},
        {"symbol": "authenticate", "file": "dist/bundle.js", "category": "BUNDLE", "score": 0.8},
    ]

    ranked = rank_candidates(candidates, query="authenticate")
    # Best candidate must be the SOURCE file
    assert ranked[0].file == "src/auth.py"
    # Check penalty reasons are present
    reasons_by_file = {r.file: [reason.code for reason in r.reasons] for r in ranked}
    assert "VENDOR_PENALTY" in reasons_by_file["vendor/library.js"]
    assert "GENERATED_PENALTY" in reasons_by_file["generated/client.py"]
    assert "BUNDLE_PENALTY" in reasons_by_file["dist/bundle.js"]


