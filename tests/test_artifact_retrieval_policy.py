def test_28_source_to_generated_classification_change(tmp_path: Path) -> None:
    """28. Modifying a file by adding a @generated header reclassifies it on incremental re-index."""
    repo = tmp_path / "trans_repo"
    repo.mkdir()
    f = repo / "module.py"
    f.write_text("def run(): return 1\n", encoding="utf-8")

    indexer = Indexer(repo)
    indexer.index()
    with indexer.session() as con:
        cat1 = con.execute("SELECT category FROM files WHERE path='module.py'").fetchone()[0]
        assert cat1 == "SOURCE"

    # Add @generated header
    f.write_text("# @generated\ndef run(): return 1\n", encoding="utf-8")
    indexer.index()
    with indexer.session() as con:
        cat2 = con.execute("SELECT category FROM files WHERE path='module.py'").fetchone()[0]
        assert cat2 == "GENERATED"


