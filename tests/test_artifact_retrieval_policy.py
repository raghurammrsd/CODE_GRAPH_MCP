def test_30_file_move_between_directories(tmp_path: Path) -> None:
    """30. Moving a file from src/ to dist/ updates its classification upon re-index."""
    repo = tmp_path / "move_repo"
    repo.mkdir()
    src_dir = repo / "src"
    src_dir.mkdir()
    f = src_dir / "worker.js"
    f.write_text("function work() { return 1; }\n", encoding="utf-8")

    indexer = Indexer(repo)
    indexer.index()
    with indexer.session() as con:
        row = con.execute("SELECT category FROM files WHERE path='src/worker.js'").fetchone()
        assert row[0] == "SOURCE"

    # Move to dist/worker.js
    f.unlink()
    dist_dir = repo / "dist"
    dist_dir.mkdir()
    (dist_dir / "worker.js").write_text("function work() { return 1; }\n", encoding="utf-8")

    indexer.index()
    with indexer.session() as con:
        old_row = con.execute("SELECT category FROM files WHERE path='src/worker.js'").fetchone()
        assert old_row is None
        assert classify_file("dist/worker.js") == FileCategory.BUILD_ARTIFACT


def test_31_deletion_cleanup(tmp_path: Path) -> None:
    """31. Deleting a file cleans up its file and symbol entries completely."""
    repo = tmp_path / "del_repo"
    repo.mkdir()
