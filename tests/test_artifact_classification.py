def test_06_minified_javascript() -> None:
    """6. Minified JS (.min.js or extreme single-line density) classifies as MINIFIED."""
    # By extension
    res_ext = classify_file_detailed("assets/jquery.min.js")
    assert res_ext.category == FileCategory.MINIFIED
    assert res_ext.reason.startswith("minified_extension")

    # By extreme single line length (> 1000 chars)
    dense_code = "var a=1;" + "function x(){return 42;}" * 100
    res_dense = classify_file_detailed("assets/logic.js", dense_code)
    assert res_dense.category == FileCategory.MINIFIED
    assert res_dense.reason == "content_density_single_line_length"


