"""Tests for Phase 8: Artifact, Generated Code & Bundle Classification.

Verifies deterministic, explainable classification of repository files into:
- SOURCE
- TEST
- GENERATED
- BUILD_ARTIFACT
- BUNDLE
- MINIFIED
- VENDOR
- CONFIG
- BINARY
- UNKNOWN
"""
from __future__ import annotations

from codegraph.indexing.classifier import (
    FileCategory,
    classify_file,
    classify_file_detailed,
)


def test_01_handwritten_source() -> None:
    """1. Handwritten source files (.py, .ts, .js) classify as SOURCE."""
    res_py = classify_file_detailed("src/services/auth.py", "def login(): pass")
    assert res_py.category == FileCategory.SOURCE
    assert res_py.reason == "handwritten_source_file"
    assert res_py.confidence == "HIGH"

    res_ts = classify_file_detailed("src/client.ts", "export function connect() {}")
    assert res_ts.category == FileCategory.SOURCE
    assert res_ts.reason == "handwritten_source_file"


def test_02_generated_header_banners() -> None:
    """2. Files with generated banners (@generated, DO NOT EDIT, etc.) classify as GENERATED."""
    py_header = "# @generated by tool. Do not edit.\ndef api_call(): pass"
    res_py = classify_file_detailed("src/api_client.py", py_header)
    assert res_py.category == FileCategory.GENERATED
    assert res_py.reason == "generated_header_banner"
    assert "api_client.py" in str(res_py.evidence) or "@generated" in str(res_py.evidence)

    ts_header = "// Code generated by protoc-gen-ts. DO NOT EDIT.\nexport interface Query {}"
    res_ts = classify_file_detailed("src/proto.ts", ts_header)
    assert res_ts.category == FileCategory.GENERATED
    assert res_ts.reason == "generated_header_banner"

    auto_gen = "/* AUTO-GENERATED FILE. DO NOT MODIFY. */\nclass Schema {}"
    res_auto = classify_file_detailed("src/schema.js", auto_gen)
    assert res_auto.category == FileCategory.GENERATED
    assert res_auto.reason == "generated_header_banner"


