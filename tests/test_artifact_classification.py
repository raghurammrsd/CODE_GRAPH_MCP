def test_04_dist_artifact() -> None:
    """4. Files under dist/ classify as BUILD_ARTIFACT."""
    res = classify_file_detailed("dist/app.js")
    assert res.category == FileCategory.BUILD_ARTIFACT
    assert res.reason.startswith("known_build_output_path")
    assert "dist" in res.evidence


def test_05_build_artifacts() -> None:
    """5. Files under build/, out/, target/, .next/ classify as BUILD_ARTIFACT."""
    for path in [
        "build/bundle.js",
        "out/main.js",
        "target/debug/app",
        ".next/server/pages/index.js",
        "coverage/lcov-report/index.html",
        "src/__pycache__/app.cpython-311.pyc",
    ]:
        res = classify_file_detailed(path)
