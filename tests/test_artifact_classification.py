def test_15_conflicting_classification_signals() -> None:
    """15. Deterministic precedence handles conflicting signals correctly:
    - Binary null byte overrides .py extension
    - Build artifact directory overrides source extension
    - Generated banner overrides source extension
    """
    # Source extension with binary bytes
    res_bin = classify_file_detailed("src/module.py", b"\x00\x01\x02")
    assert res_bin.category == FileCategory.BINARY

    # Source extension in dist directory
    res_build = classify_file_detailed("dist/module.py", "def fn(): pass")
    assert res_build.category == FileCategory.BUILD_ARTIFACT

    # Source extension with generated header banner
    res_gen = classify_file_detailed("src/api.py", "# @generated\ndef fn(): pass")
    assert res_gen.category == FileCategory.GENERATED

    # Vendor directory overrides test filename
    res_vendor_test = classify_file_detailed("node_modules/pkg/tests/test_foo.js")
    assert res_vendor_test.category == FileCategory.VENDOR


def test_16_backward_compatibility() -> None:
    """16. Backward compatibility: classify_file returns FileCategory enum that equals GENERATED for legacy code."""
    assert classify_file("src/main.py") == FileCategory.SOURCE
    assert classify_file("tests/test_auth.py") == FileCategory.TEST
    assert classify_file("app.min.js") == FileCategory.MINIFIED
    assert classify_file("app.min.js") == "GENERATED"
    assert classify_file("app.bundle.js") == FileCategory.BUNDLE
    assert classify_file("app.bundle.js") == "GENERATED"
